-- vncviewer runs via XWayland, so it can't use the native Wayland
-- shortcuts-inhibit protocol to grab mainMod+<digit> etc. away from our
-- own global binds. sync_vnc_passthrough() (defined next to mainMod)
-- swaps to this (almost) empty submap instead, but only while vncviewer
-- is genuinely fullscreen; mainMod+Escape is a manual escape hatch back
-- to normal binds in case fullscreen-state detection ever misfires.
hl.define_submap("vnc-passthrough", function()
    hl.bind(mainMod .. " + Escape", hl.dsp.submap(""))
end)

-- Covers focus moving onto/off of vncviewer (e.g. switching workspaces
-- back to it while it was left fullscreen); the mainMod+F bind covers
-- toggling fullscreen via our own bind while it's already focused.
hl.on("window.active", function(w)
    sync_vnc_passthrough()
end)

-- Also covers leaving fullscreen by any OTHER means (e.g. TigerVNC's own
-- ctrl+alt+enter), which bypasses mainMod+F entirely once passthrough is
-- active -- without this, the submap stays stuck until focus changes.
hl.on("window.fullscreen", function(w)
    sync_vnc_passthrough()
end)

