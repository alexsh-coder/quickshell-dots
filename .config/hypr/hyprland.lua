-- Switches to the "vnc-passthrough" submap (defined further down) so
-- mainMod+<digit> etc. reach the remote session instead of switching
-- workspaces here, but only while vncviewer is actually fullscreen --
-- windowed, mainMod+SHIFT+<digit> etc. still move/manage it like any
-- other window.
local function sync_vnc_passthrough()
    local w = hl.get_active_window()
    -- w.fullscreen is a number (0/1), not a bool -- in Lua, 0 is truthy,
    -- so this must be an explicit comparison or it's always "fullscreen".
    if w and w.class == "Vncviewer" and w.fullscreen ~= 0 then
        hl.dispatch(hl.dsp.submap("vnc-passthrough"))
    else
        hl.dispatch(hl.dsp.submap(""))
    end
end

